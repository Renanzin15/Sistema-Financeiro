class NovoOrcamento(BaseModel):
    categoria: str
    mes: str            # AAAA-MM
    limite_centavos: int

def _mes_valido(mes):
    return bool(re.match(r"^\d{4}-\d{2}$", mes or "")) and 1 <= int(mes[5:7]) <= 12

def _mes_atual():
    return date.today().strftime("%Y-%m")

def limite_categoria(con, user_id, categoria, mes):
    """Limite vigente da categoria naquele mês: a linha mais recente com mes <= o mês pedido
    (regra 'vale deste mês em diante'). Retorna centavos ou None se nunca houve teto até ali."""
    linha = con.execute(
        "SELECT limite_centavos FROM orcamentos WHERE user_id=? AND lower(categoria)=lower(?) "
        "AND mes<=? ORDER BY mes DESC LIMIT 1", (user_id, categoria, mes)
    ).fetchone()
    return linha[0] if linha else None

def gasto_por_categoria(con, user_id, mes):
    """Quanto foi gasto por categoria naquele mês (AAAA-MM). Soma:
    - gasto livre (saida_livre) pela sua categoria;
    - dívidas pagas (pagamento) pela categoria (tipo) da conta que ele quitou.
    Retorna dict {categoria_minuscula: centavos}. Lançamentos sem data ou sem categoria ficam de fora."""
    total = {}
    # gasto livre com categoria preenchida
    for cat, cents in con.execute(
        "SELECT categoria, COALESCE(SUM(valor_centavos),0) FROM lancamentos "
        "WHERE user_id=? AND tipo='saida_livre' AND categoria IS NOT NULL AND categoria<>'' "
        "AND substr(data,1,7)=? GROUP BY categoria", (user_id, mes)
    ).fetchall():
        if cat:
            total[cat.lower()] = total.get(cat.lower(), 0) + cents
    # dívidas pagas: categoria vem do 'tipo' da conta ligada (conta_paga_id)
    for cat, cents in con.execute(
        "SELECT c.tipo, COALESCE(SUM(l.valor_centavos),0) FROM lancamentos l "
        "JOIN contas c ON c.id=l.conta_paga_id AND c.user_id=l.user_id "
        "WHERE l.user_id=? AND l.tipo='pagamento' AND l.conta_paga_id IS NOT NULL "
        "AND substr(l.data,1,7)=? GROUP BY c.tipo", (user_id, mes)
    ).fetchall():
        if cat:
            total[cat.lower()] = total.get(cat.lower(), 0) + cents
    return total

@app.get("/orcamento")
def ver_orcamento(mes: str | None = None, user_id: str = Depends(exigir_login)):
    """Resumo do orçamento do mês: para cada categoria, limite vigente, quanto foi gasto,
    quanto resta, % consumido e status (verde/amarelo>=80%/vermelho estourou)."""
    mes = mes or _mes_atual()
    if not _mes_valido(mes):
        raise HTTPException(status_code=400, detail="Mês inválido (use AAAA-MM).")
    con = conectar()
    cats = [l[0] for l in con.execute(
        "SELECT nome FROM categorias WHERE user_id=? ORDER BY nome", (user_id,)
    ).fetchall()]
    gastos = gasto_por_categoria(con, user_id, mes)
    itens = []
    total_limite = total_gasto = 0
    for nome in cats:
        limite = limite_categoria(con, user_id, nome, mes)
        gasto = gastos.get(nome.lower(), 0)
        # razão crua decide o status (evita que 79,6% já vire alerta por arredondamento);
        # o pct exibido é só pra tela.
        razao = (gasto / limite) if limite else None
        pct = int(razao * 100 + 0.5) if limite else None   # arredonda meio-pra-cima (não bancário)
        if limite is None:
            status = "sem_teto"
        elif gasto > limite:
            status = "estourou"
        elif razao >= 0.8:
            status = "atencao"
        else:
            status = "ok"
        itens.append({
            "categoria": nome,
            "limite_centavos": limite,
            "gasto_centavos": gasto,
            "restante_centavos": (limite - gasto) if limite is not None else None,
            "pct": pct,
            "status": status,
        })
        if limite is not None:
            total_limite += limite
            total_gasto += gasto
    con.close()
    # ordena: categorias com teto primeiro (as sem teto vão pro fim)
    itens.sort(key=lambda i: (i["limite_centavos"] is None, i["categoria"].lower()))
    return {
        "mes": mes,
        "itens": itens,
        "total_limite_centavos": total_limite,
        "total_gasto_centavos": total_gasto,
    }

