# ROTAS DE CARTÃO DE CRÉDITO (Mudança 5)
# Um cartão tem limite + dia de fechamento + dia de vencimento. As faturas mensais são
# contas tipo_conta='fatura' ligadas ao cartão (cartao_id) e marcadas com a competência (AAAA-MM).
# Compra até o fechamento cai na fatura do mês; depois do fechamento, na do mês seguinte.
# ========================================================

_MESES_ABREV = ["jan", "fev", "mar", "abr", "mai", "jun", "jul", "ago", "set", "out", "nov", "dez"]

def _competencia_label(comp):
    return f"{_MESES_ABREV[int(comp[5:7]) - 1]}/{comp[:4]}"

def _competencia_compra(data_iso, dia_fechamento):
    """Em qual fatura (AAAA-MM) uma compra cai: até o dia de fechamento vai pro mês da compra;
    depois do fechamento, vai pro mês seguinte."""
    d = datetime.strptime(data_iso, "%Y-%m-%d").date()
    if d.day <= dia_fechamento:
        y, m = d.year, d.month
    else:
        y, m = (d.year + 1, 1) if d.month == 12 else (d.year, d.month + 1)
    return f"{y:04d}-{m:02d}"

def _somar_meses(comp, n):
    total = int(comp[:4]) * 12 + (int(comp[5:7]) - 1) + n
    return f"{total // 12:04d}-{total % 12 + 1:02d}"

def _vencimento_fatura(comp, dia_fechamento, dia_vencimento):
    """Data de vencimento da fatura daquela competência. Se o vencimento vem depois do fechamento,
    vence no mês da competência; senão (ex.: fecha 25, vence 5), vence no mês seguinte."""
    y, m = int(comp[:4]), int(comp[5:7])
    if dia_vencimento <= dia_fechamento:
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return _dia_no_mes(y, m, dia_vencimento)

def _achar_ou_criar_fatura(con, user_id, cartao_id, comp):
    """Devolve (fatura_id, paga) da fatura do cartão naquela competência, criando se não existir."""
    row = con.execute(
        "SELECT id, paga FROM contas WHERE user_id=? AND cartao_id=? AND competencia=? AND tipo_conta='fatura'",
        (user_id, cartao_id, comp)
    ).fetchone()
    if row:
        return row[0], row[1]
    cart = con.execute(
        "SELECT nome, dia_fechamento, dia_vencimento FROM cartoes WHERE id=? AND user_id=?", (cartao_id, user_id)
    ).fetchone()
    if not cart:
        return None, None
    nome, fech, venc = cart
    vencimento = _vencimento_fatura(comp, fech, venc)
    con.execute(
        "INSERT INTO contas (nome, valor_centavos, vencimento, tipo, paga, tipo_conta, cartao_id, competencia, user_id) "
        "VALUES (?, 0, ?, 'Cartão', 0, 'fatura', ?, ?, ?)",
        (f"{nome} · {_competencia_label(comp)}", vencimento, cartao_id, comp, user_id)
    )
    fid = con.execute(
        "SELECT id FROM contas WHERE user_id=? AND cartao_id=? AND competencia=? AND tipo_conta='fatura'",
        (user_id, cartao_id, comp)
    ).fetchone()[0]
    return fid, 0

def _usado_cartao(con, user_id, cartao_id):
    """Total ainda em aberto no cartão = soma dos itens de todas as faturas NÃO pagas
    (inclui parcelas futuras já lançadas)."""
    return con.execute(
        "SELECT COALESCE(SUM(fi.valor_centavos),0) FROM fatura_itens fi "
        "JOIN contas c ON c.id=fi.conta_id AND c.user_id=fi.user_id "
        "WHERE c.user_id=? AND c.cartao_id=? AND c.paga=0", (user_id, cartao_id)
    ).fetchone()[0]

