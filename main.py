def _num_br(s):
    """Converte um texto monetário (formatos BR e US) em float, ou None se não for número."""
    s = (s or "").strip().replace("R$", "").replace(" ", "")
    if not s:
        return None
    neg = s.startswith("-") or s.startswith("(")
    s2 = s.replace("(", "").replace(")", "").replace("+", "").lstrip("-")
    if "," in s2 and "." in s2:
        s2 = s2.replace(".", "").replace(",", ".")   # 1.234,56 -> 1234.56
    elif "," in s2:
        s2 = s2.replace(",", ".")                     # 1234,56 -> 1234.56
    try:
        v = float(s2)
    except ValueError:
        return None
    return -v if neg else v

def _data_iso(s):
    """Normaliza datas comuns (dd/mm/aaaa, aaaa-mm-dd, dd/mm/aa) para AAAA-MM-DD, ou '?'."""
    s = (s or "").strip()
    m = re.match(r"^(\d{2})/(\d{2})/(\d{4})$", s)
    if m:
        return f"{m.group(3)}-{m.group(2)}-{m.group(1)}"
    if re.match(r"^\d{4}-\d{2}-\d{2}$", s):
        return s
    m = re.match(r"^(\d{2})/(\d{2})/(\d{2})$", s)
    if m:
        return f"20{m.group(3)}-{m.group(2)}-{m.group(1)}"
    return "?"

def _sugerir_caixinha(descricao, caixinhas):
    """caixinhas = lista de (id, nome_minusculo). Retorna o id sugerido ou None."""
    d = (descricao or "").lower()
    for cid, nome in caixinhas:
        if nome and nome in d:
            return cid
    for palavra, categoria in MAPA_PALAVRAS.items():
        if palavra in d:
            for cid, nome in caixinhas:
                if nome == categoria:
                    return cid
    return None

def parse_ofx(texto, caixinhas):
    linhas = []
    for bloco in re.findall(r"<STMTTRN>(.*?)</STMTTRN>", texto, re.S | re.I):
        m_val = re.search(r"<TRNAMT>([^<\r\n]+)", bloco, re.I)
        if not m_val:
            continue
        valor = _num_br(m_val.group(1))
        if valor is None:
            continue
        m_dt = re.search(r"<DTPOSTED>(\d{8})", bloco, re.I)
        data = "?"
        if m_dt:
            g = m_dt.group(1)
            data = f"{g[0:4]}-{g[4:6]}-{g[6:8]}"
        m_memo = re.search(r"<MEMO>([^<\r\n]+)", bloco, re.I)
        m_name = re.search(r"<NAME>([^<\r\n]+)", bloco, re.I)
        desc = (m_memo.group(1) if m_memo else (m_name.group(1) if m_name else "lançamento")).strip()
        cents = abs(round(valor * 100))
        if cents == 0:
            continue
        linhas.append({
            "descricao": desc[:80],
            "valor_centavos": cents,
            "data": data,
            "tipo": "entrada" if valor > 0 else "pagamento",
            "caixinha_id": _sugerir_caixinha(desc, caixinhas),
        })
    return linhas

def parse_csv(texto, caixinhas):
    amostra = texto[:3000]
    delim = ";" if amostra.count(";") >= amostra.count(",") else ","
    linhas_raw = [r for r in csv.reader(io.StringIO(texto), delimiter=delim) if any((c or "").strip() for c in r)]
    if not linhas_raw:
        return []

    def achar(hs, termos):
        for i, h in enumerate(hs):
            for t in termos:
                if t in h:
                    return i
        return None

    header = [(c or "").strip().lower() for c in linhas_raw[0]]
    i_data = achar(header, ["data", "date"])
    i_valor = achar(header, ["valor", "amount", "quantia", "montante", "value"])
    i_desc = achar(header, ["descri", "histor", "lanç", "lanc", "memo", "estabelec", "title", "detalhe"])
    tem_cabecalho = (i_data is not None) or (i_valor is not None)
    corpo = linhas_raw[1:] if tem_cabecalho else linhas_raw

    linhas = []
    for r in corpo:
        valor = None
        data = "?"
        desc = "lançamento"
        if i_valor is not None and i_valor < len(r):
            valor = _num_br(r[i_valor])
            if i_data is not None and i_data < len(r):
                data = _data_iso(r[i_data])
            if i_desc is not None and i_desc < len(r):
                desc = (r[i_desc] or "").strip() or "lançamento"
        else:
            # heurística posicional: acha um token de data e um token monetário (com , ou .)
            partes = []
            for cel in r:
                c = (cel or "").strip()
                if data == "?" and _data_iso(c) != "?":
                    data = _data_iso(c); continue
                if valor is None and ("," in c or "." in c) and _num_br(c) is not None:
                    valor = _num_br(c); continue
                partes.append(c)
            desc = " ".join(p for p in partes if p) or "lançamento"
        if valor is None:
            continue
        cents = abs(round(valor * 100))
        if cents == 0:
            continue
        linhas.append({
            "descricao": desc[:80],
            "valor_centavos": cents,
            "data": data,
            "tipo": "entrada" if valor > 0 else "pagamento",
            "caixinha_id": _sugerir_caixinha(desc, caixinhas),
        })
    return linhas


