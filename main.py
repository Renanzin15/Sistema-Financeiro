                        if ja_item is None:
                            con.execute(
                                "INSERT INTO fatura_itens (conta_id, descricao, valor_centavos, data, user_id) VALUES (?, ?, ?, ?, ?)",
                                (fatura_id, nome, valor, vencimento, user_id)
                            )
