@app.post("/lancamentos")
def criar_lancamento(item: NovoLancamento, user_id: str = Depends(exigir_login)):
    # validações de entrada
    if item.valor_centavos <= 0:
        raise HTTPException(status_code=400, detail="O valor precisa ser maior que zero.")
    if not data_valida(item.data):
        raise HTTPException(status_code=400, detail="Data inválida (use AAAA-MM-DD, ano entre 2000 e 2100).")
    con = conectar()

    # Trava de saldo: não deixar guardar/gastar sem dinheiro.
    # - alocacao (guardar na caixinha) e saida_livre (gasto do saldo livre) saem do SALDO LIVRE.
    # - pagamento (gastar de uma caixinha) sai do SALDO DAQUELA CAIXINHA.
    # entrada e rendimento adicionam dinheiro, não precisam de trava.
    if item.tipo in ("alocacao", "saida_livre"):
        livre = calcular_saldo_livre(con, user_id)
        if item.valor_centavos > livre:
            con.close()
            acao = "guardar" if item.tipo == "alocacao" else "gastar"
            raise HTTPException(
                status_code=400,
                detail=f"Saldo livre insuficiente para {acao}: você tem R$ {livre/100:.2f} livre."
            )
    elif item.tipo == "pagamento":
        if not item.caixinha_id:
            con.close()
            raise HTTPException(status_code=400, detail="Escolha de qual caixinha vai sair o gasto.")
        saldo = saldo_da_caixinha(con, user_id, item.caixinha_id)
        if item.valor_centavos > saldo:
            con.close()
            raise HTTPException(
                status_code=400,
                detail=f"Saldo insuficiente nessa caixinha: ela tem R$ {saldo/100:.2f}."
            )

    # usa a data escolhida (se veio) ou a de hoje
    data = item.data if item.data else data_hoje()
    # M2: só o gasto livre carrega categoria. Se veio vazia, tenta adivinhar pela descrição
    # (uber->transporte, ifood->alimentação...), mas só se bater com uma categoria que o usuário tem.
    categoria = None
    if item.tipo == "saida_livre":
        categoria = (item.categoria or "").strip() or None
        if not categoria:
            categoria = sugerir_categoria(con, user_id, item.descricao)
    con.execute(
        "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, categoria, user_id) VALUES (?, ?, ?, ?, ?, ?, ?)",
        (item.tipo, item.valor_centavos, item.descricao, item.caixinha_id, data, categoria, user_id)
    )
    # M9: aprende a categoria confirmada pra essa descrição (pra sugerir sozinho da próxima vez)
    if item.tipo == "saida_livre" and categoria and item.descricao:
        _aprender_categoria(con, user_id, item.descricao, categoria)
    # E4: entradas disparam as regras de salário (alocações automáticas)
    if item.tipo == "entrada":
        aplicar_regras_salario(con, user_id, item.descricao, item.valor_centavos, data)
    con.commit()
    con.close()
    return {"status": "salvo"}

