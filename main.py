@app.post("/importar/analisar")
def importar_analisar(item: ImportarAnalise, user_id: str = Depends(exigir_login)):
    con = conectar()
    caixinhas = [(c[0], (c[1] or "").lower()) for c in con.execute("SELECT id, nome FROM caixinhas WHERE user_id=?", (user_id,)).fetchall()]
    con.close()
    if item.tipo_arquivo == "ofx":
        linhas = parse_ofx(item.conteudo, caixinhas)
    else:
        linhas = parse_csv(item.conteudo, caixinhas)
    return {"linhas": linhas, "total": len(linhas)}

@app.post("/importar/conta-imagem")
def importar_conta_imagem(item: ImportarContaImagem, user_id: str = Depends(exigir_login)):
    """Lê uma foto/print ou PDF de conta e devolve uma prévia (nome, valor, vencimento)
    pra o usuário conferir/corrigir antes de criar a conta de verdade via POST /contas."""
    if not OCR_DISPONIVEL:
        raise HTTPException(
            status_code=500,
            detail="Leitor de conta por imagem não está instalado neste servidor. "
                    "Rode: pip install pytesseract Pillow PyMuPDF, e instale o Tesseract "
                    "(ver estudo_ocr_conta_imagem.md)."
        )
    conteudo = item.conteudo
    if "," in conteudo and conteudo.strip().startswith("data:"):
        conteudo = conteudo.split(",", 1)[1]  # tira o prefixo "data:...;base64,"
    try:
        dados = base64.b64decode(conteudo)
    except Exception:
        raise HTTPException(status_code=400, detail="Arquivo inválido (falha ao decodificar).")
    if len(dados) > TAMANHO_MAX_ARQUIVO_OCR:
        raise HTTPException(status_code=400, detail="Arquivo grande demais (máximo 15 MB).")
    if not dados:
        raise HTTPException(status_code=400, detail="Arquivo vazio.")

    try:
        if item.tipo_arquivo == "pdf":
            texto = ocr_texto_pdf(dados)
        else:
            texto = ocr_texto_imagem(dados)
    except pytesseract.TesseractNotFoundError:
        raise HTTPException(
            status_code=500,
            detail="Tesseract não encontrado no caminho configurado. Verifique a instalação "
                    "(ver estudo_ocr_conta_imagem.md) ou defina a variável de ambiente TESSERACT_CMD."
        )
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Não consegui ler o arquivo: {e}")

    if not texto.strip():
        raise HTTPException(status_code=400, detail="Não consegui ler nenhum texto nesse arquivo. Tente uma foto mais nítida.")

    return extrair_conta(texto)

@app.post("/importar/confirmar")
def importar_confirmar(item: ImportarConfirmar, user_id: str = Depends(exigir_login)):
    con = conectar()
    n = 0
    for l in item.linhas:
        if l.valor_centavos <= 0:
            continue
        data = l.data if re.match(r"^\d{4}-\d{2}-\d{2}$", l.data or "") else data_hoje()
        # só usa a caixinha se ela for do próprio usuário (senão vira saída livre)
        cx_ok = l.caixinha_id and con.execute(
            "SELECT id FROM caixinhas WHERE id=? AND user_id=?", (l.caixinha_id, user_id)
        ).fetchone() is not None
        if l.tipo == "entrada":
            # entrada importada NÃO dispara regras de salário (é histórico); vai pro saldo livre
            con.execute(
                "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, user_id) VALUES ('entrada', ?, ?, NULL, ?, ?)",
                (l.valor_centavos, l.descricao, data, user_id)
            )
        elif cx_ok:
            con.execute(
                "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, user_id) VALUES ('pagamento', ?, ?, ?, ?, ?)",
                (l.valor_centavos, l.descricao, l.caixinha_id, data, user_id)
            )
        else:
            con.execute(
                "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, user_id) VALUES ('saida_livre', ?, ?, NULL, ?, ?)",
                (l.valor_centavos, l.descricao, data, user_id)
            )
        n += 1
    con.commit()
    con.close()
    return {"status": "importado", "quantidade": n}
