def _contas_a_pagar(con, user_id):
    """(total_restante_centavos, qtd, proxima_venc_iso|None) das contas/faturas em aberto."""
    total = qtd = 0
    proxima = None
    for cid, valor, venc, tipo_conta in con.execute(
        "SELECT id, valor_centavos, vencimento, tipo_conta FROM contas "
        "WHERE user_id=? AND paga=0 AND COALESCE(arquivada,0)=0", (user_id,)
    ).fetchall():
        t = total_conta(con, user_id, cid, tipo_conta or "simples", valor)
        restante = t - total_pago_conta(con, user_id, cid)
        if restante <= 0:
            continue
        total += restante
        qtd += 1
        if venc and (proxima is None or venc < proxima):
            proxima = venc
    return total, qtd, proxima

@app.get("/assistente")
def assistente(q: str, categoria: str = None, valor_centavos: int = 0, parcelas: int = 1,
               cartao_id: int = None, user_id: str = Depends(exigir_login)):
    """Responde uma pergunta pré-definida com número calculado (exato)."""
    con = conectar()
    hoje = date.today()
    mes = hoje.strftime("%Y-%m")
    resposta = "Não entendi a pergunta."

    if q == "sobra":
        livre = calcular_saldo_livre(con, user_id)
        t = totais_mes(con, user_id, mes)
        resposta = (f"Você tem {reais_txt(livre)} livres agora. Este mês entraram {reais_txt(t['entrou_centavos'])} "
                    f"e saíram {reais_txt(t['saiu_centavos'])}, sobrando {reais_txt(t['sobrou_centavos'])} até aqui.")

    elif q == "resumo":
        t = totais_mes(con, user_id, mes)
        gasto = gasto_por_categoria(con, user_id, mes)
        extra = ""
        if gasto:
            maior = max(gasto.items(), key=lambda kv: kv[1])
            if maior[1] > 0:
                extra = f" Sua maior despesa é {_nome_categoria_real(con, user_id, maior[0])} ({reais_txt(maior[1])})."
        resposta = (f"Resumo de {_competencia_label(mes)}: entrou {reais_txt(t['entrou_centavos'])}, "
                    f"saiu {reais_txt(t['saiu_centavos'])}, sobrou {reais_txt(t['sobrou_centavos'])}.{extra}")

    elif q == "pagar":
        total, qtd, proxima = _contas_a_pagar(con, user_id)
        if qtd == 0:
            resposta = "Você não tem contas em aberto. 🎉"
        else:
            resposta = f"Você tem {reais_txt(total)} a pagar em {qtd} conta(s)/fatura(s) em aberto."
            if proxima:
                resposta += f" A próxima vence em {_fmt_data_br(proxima)}."

    elif q == "gasto_categoria":
        if not categoria:
            con.close()
            raise HTTPException(status_code=400, detail="Escolha a categoria.")
        g = gasto_por_categoria(con, user_id, mes).get(categoria.lower(), 0)
        nome = _nome_categoria_real(con, user_id, categoria)
        limite = limite_categoria(con, user_id, nome, mes)
        if limite:
            if g > limite:
                resposta = f"Em {nome} você já gastou {reais_txt(g)} este mês — {reais_txt(g - limite)} acima do teto de {reais_txt(limite)}. 🔴"
            else:
                resposta = f"Em {nome} você gastou {reais_txt(g)} este mês, de um teto de {reais_txt(limite)} (resta {reais_txt(limite - g)})."
        else:
            resposta = f"Em {nome} você gastou {reais_txt(g)} este mês. (Sem teto definido — dá pra criar no Orçamento.)"

    elif q == "posso_comprar":
        if valor_centavos <= 0:
            con.close()
            raise HTTPException(status_code=400, detail="Informe o valor da compra.")
        livre = calcular_saldo_livre(con, user_id)
        if cartao_id:
            cart = con.execute("SELECT nome, limite_centavos FROM cartoes WHERE id=? AND user_id=?", (cartao_id, user_id)).fetchone()
            if cart is None:
                con.close()
                raise HTTPException(status_code=404, detail="Cartão não encontrado.")
            disp = cart[1] - _usado_cartao(con, user_id, cartao_id)
            n = max(parcelas, 1)
            parcela = valor_centavos // n
            if valor_centavos > disp:
                resposta = f"No {cart[0]} não cabe: o disponível é {reais_txt(disp)} e a compra é {reais_txt(valor_centavos)}."
            else:
                extra_p = f" em {n}x de ~{reais_txt(parcela)}" if n > 1 else ""
                resposta = (f"Cabe no {cart[0]}{extra_p}. Disponível depois: {reais_txt(disp - valor_centavos)}. "
                            f"Lembre que a fatura vem no próximo ciclo.")
        else:
            if valor_centavos > livre:
                resposta = f"À vista não dá: você tem {reais_txt(livre)} livres e a compra é {reais_txt(valor_centavos)}. Talvez parcelar no cartão?"
            else:
                proj = None
                try:
                    ate = _dia_no_mes(hoje.year, hoje.month, calendar.monthrange(hoje.year, hoje.month)[1])
                    proj = projetar_financas(user_id, ate).get("saldo_projetado_centavos")
                except Exception:
                    proj = None
                if proj is not None and (proj - valor_centavos) < 0:
                    resposta = (f"Cabe no saldo hoje (sobrariam {reais_txt(livre - valor_centavos)}), mas o mês fecharia "
                                f"no negativo com contas previstas. Melhor esperar ou parcelar.")
                else:
                    resposta = f"Pode! Cabe no saldo livre e sobrariam {reais_txt(livre - valor_centavos)}. O mês segue positivo. 👍"

    con.close()
    return {"resposta": resposta}


