def _iter_meses(inicio, fim):
    """(ano, mes) do mês de `inicio` até o mês de `fim`, inclusive (ambos date)."""
    y, m = inicio.year, inicio.month
    while (y, m) <= (fim.year, fim.month):
        yield y, m
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)

