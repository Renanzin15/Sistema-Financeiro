# adiciona colunas novas a tabelas que já existem, sem apagar dados.
# só adiciona se a coluna ainda não existir (senão o ALTER daria erro na 2ª vez).
def migrar():
    if USA_POSTGRES:
        return  # no Postgres a DDL de criar_tabelas() já cria as tabelas completas
    con = conectar()
    # quais colunas a tabela caixinhas já tem?
    colunas = [c[1] for c in con.execute("PRAGMA table_info(caixinhas)").fetchall()]
    if "banco_id" not in colunas:
        con.execute("ALTER TABLE caixinhas ADD COLUMN banco_id INTEGER")
    # F1: passar a guardar a DATA de cada lançamento (só os novos terão data;
    # os antigos ficam com NULL, pois não dá pra inventar quando aconteceram).
    colunas_lanc = [c[1] for c in con.execute("PRAGMA table_info(lancamentos)").fetchall()]
    if "data" not in colunas_lanc:
        con.execute("ALTER TABLE lancamentos ADD COLUMN data TEXT")
    # D: tipo da conta — "simples" (valor único) ou "fatura" (soma de itens).
    # Contas antigas assumem "simples" (DEFAULT), preservando o comportamento atual.
    colunas_contas = [c[1] for c in con.execute("PRAGMA table_info(contas)").fetchall()]
    if "tipo_conta" not in colunas_contas:
        con.execute("ALTER TABLE contas ADD COLUMN tipo_conta TEXT DEFAULT 'simples'")
    # Metas: valor-alvo opcional de cada caixinha (0 = sem meta).
    if "meta_centavos" not in colunas:
        con.execute("ALTER TABLE caixinhas ADD COLUMN meta_centavos INTEGER DEFAULT 0")
    # E8: data-limite opcional da meta (AAAA-MM-DD). Vazio = meta sem prazo.
    if "meta_prazo" not in colunas:
        con.execute("ALTER TABLE caixinhas ADD COLUMN meta_prazo TEXT")
    # M1: arquivar (não apagar) contas pagas pra limpar a tela sem perder o histórico.
    if "arquivada" not in colunas_contas:
        con.execute("ALTER TABLE contas ADD COLUMN arquivada INTEGER DEFAULT 0")
    # E2: vínculo da assinatura com uma fatura de cartão (FK). Vazio = conta avulsa.
    colunas_rec = [c[1] for c in con.execute("PRAGMA table_info(recorrentes)").fetchall()]
    if "conta_fatura_id" not in colunas_rec:
        con.execute("ALTER TABLE recorrentes ADD COLUMN conta_fatura_id INTEGER")
    # multi-usuário: user_id em todas as tabelas de dados (SQLite local)
    for _t in ("bancos", "caixinhas", "lancamentos", "contas", "recorrentes", "fatura_itens", "categorias", "regras_salario"):
        _cols = [c[1] for c in con.execute(f"PRAGMA table_info({_t})").fetchall()]
        if "user_id" not in _cols:
            con.execute(f"ALTER TABLE {_t} ADD COLUMN user_id TEXT")
    con.commit()
    con.close()

# ---- autenticação: Supabase Auth ----
# O front faz login no Supabase (e-mail/senha; signups desativados no painel) e envia o
# access_token (JWT) no header Authorization. Aqui a gente VERIFICA esse token e extrai o
# `sub` = UUID do usuário. Projetos novos do Supabase assinam com ES256 (chave assimétrica,
# publicada no JWKS); os antigos usam HS256 (a JWT Secret). Suportamos os dois.

SUPABASE_URL = os.environ.get("SUPABASE_URL", "").rstrip("/")
SUPABASE_PUBLISHABLE_KEY = os.environ.get("SUPABASE_PUBLISHABLE_KEY", "")
SUPABASE_JWT_SECRET = os.environ.get("SUPABASE_JWT_SECRET")

# JWKS do Supabase (chaves públicas ES256) — buscado 1x e cacheado.
_jwks_cache = None
def _supabase_jwks():
    global _jwks_cache
    if _jwks_cache is None and SUPABASE_URL:
        import urllib.request, json as _json
        try:
            req = urllib.request.Request(
                SUPABASE_URL + "/auth/v1/.well-known/jwks.json",
                headers={"apikey": SUPABASE_PUBLISHABLE_KEY} if SUPABASE_PUBLISHABLE_KEY else {},
            )
            with urllib.request.urlopen(req, timeout=10) as r:
                _jwks_cache = _json.loads(r.read().decode())
        except Exception:
            _jwks_cache = None
    return _jwks_cache

def _verificar_token(tok):
    """Verifica o access_token do Supabase: tenta ES256 (JWKS) e cai pra HS256 (JWT Secret)."""
    global _jwks_cache
    try:
        kid = jwt.get_unverified_header(tok).get("kid")
    except Exception:
        kid = None
    for tentativa in (1, 2):
        jwks = _supabase_jwks()
        if jwks:
            keys = jwks.get("keys", [])
            chave = next((k for k in keys if k.get("kid") == kid), None) or (keys[0] if keys else None)
            if chave:
                try:
                    return jwt.decode(tok, chave, algorithms=["ES256"], audience="authenticated")
                except JWTError:
                    pass
        if tentativa == 1:
            _jwks_cache = None  # a chave pode ter rotacionado; recarrega o JWKS uma vez
    if SUPABASE_JWT_SECRET:
        return jwt.decode(tok, SUPABASE_JWT_SECRET, algorithms=["HS256"], audience="authenticated")
    raise JWTError("nenhuma chave disponível para verificar o token")

_usuarios_prontos = set()  # cache dos usuários que já receberam suas categorias padrão

def _garantir_usuario(user_id):
    # semeia as categorias padrão UMA vez por usuário (na 1ª vez que ele acessa)
    if user_id in _usuarios_prontos:
        return
    con = conectar()
    ja = con.execute(
        "SELECT valor FROM config WHERE user_id=? AND chave='categorias_iniciadas'", (user_id,)
    ).fetchone()
    if ja is None:
        for nome in ("Conta fixa", "Cartão", "Outros"):
            con.execute("INSERT INTO categorias (nome, user_id) VALUES (?, ?)", (nome, user_id))
        _upsert_config(con, user_id, "categorias_iniciadas", "1")
        con.commit()
    con.close()
    _usuarios_prontos.add(user_id)

# dependência que protege as rotas: exige um token válido do Supabase e devolve o user_id
def exigir_login(cred: HTTPAuthorizationCredentials = Depends(seguranca)):
    if cred is None:
        raise HTTPException(status_code=401, detail="Não autenticado.")
    try:
        dados = _verificar_token(cred.credentials)
    except Exception:
        raise HTTPException(status_code=401, detail="Sessão inválida ou expirada.")
    user_id = dados.get("sub")
    if not user_id:
        raise HTTPException(status_code=401, detail="Token sem usuário.")
    _garantir_usuario(user_id)
    return user_id

