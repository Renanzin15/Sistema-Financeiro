def _num_br(s):
    """Converte um texto monetário (formatos BR e US) em float, ou None se não for número."""
    s = (s or "").strip().replace("R$", "").replace(" ", "")
    if not s:
        return None
    neg = s.startswith("-") or s.startswith("(")
    s2 = s.replace("(", "").replace(")", "").replace("+", "").lstrip("-")
    if "," in s2 and "." in s2:
        s2 = s2.replace(".", "").replace(",", ".")   # 1.234,56 -> 1234.56
    elif "," in s2:
        s2 = s2.replace(",", ".")                     # 1234,56 -> 1234.56
    try:
        v = float(s2)
    except ValueError:
        return None
    return -v if neg else v

_MESES_PT = {"jan": "01", "fev": "02", "mar": "03", "abr": "04", "mai": "05", "jun": "06",
             "jul": "07", "ago": "08", "set": "09", "out": "10", "nov": "11", "dez": "12"}

def _data_iso(s):
    """Normaliza datas de extrato para AAAA-MM-DD (ou '?'). Cobre vários formatos de banco:
    aaaa-mm-dd (com ou sem hora), aaaa/mm/dd, dd/mm/aaaa, dd-mm-aaaa, dd.mm.aaaa, dd/mm/aa,
    e 'dd mmm[ aaaa]' / 'dd de mmm[ de aaaa]' em português (ex.: '15 ago 2026')."""
    s = (s or "").strip()
    if not s:
        return "?"
    # ISO (pega só a data, ignora hora): aaaa-mm-dd... ou aaaa/mm/dd...
    m = re.match(r"^(\d{4})[/-](\d{2})[/-](\d{2})", s)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"
    # dd[/-.]mm[/-.]aaaa
    m = re.match(r"^(\d{2})[/\-.](\d{2})[/\-.](\d{4})$", s)
    if m:
        return f"{m.group(3)}-{m.group(2)}-{m.group(1)}"
    # dd[/-.]mm[/-.]aa
    m = re.match(r"^(\d{2})[/\-.](\d{2})[/\-.](\d{2})$", s)
    if m:
        return f"20{m.group(3)}-{m.group(2)}-{m.group(1)}"
    # dd mmm[ aaaa] / dd de mmm[ de aaaa] (mês em texto, pt)
    m = re.match(r"^(\d{1,2})\s*(?:de\s+)?([a-zç]{3})[a-zç]*\.?(?:\s+(?:de\s+)?(\d{4}))?$", s.lower())
    if m and m.group(2) in _MESES_PT:
        ano = m.group(3) or str(date.today().year)
        return f"{ano}-{_MESES_PT[m.group(2)]}-{int(m.group(1)):02d}"
    return "?"

def _norm_desc(s):
    """Normaliza a descrição pra casar o aprendizado: minúsculas, sem espaços sobrando."""
    return re.sub(r"\s+", " ", (s or "").strip().lower())

def _aprender_categoria(con, user_id, descricao, categoria):
    """M9: guarda/atualiza 'descrição -> categoria' que o usuário confirmou (1 por descrição)."""
    norm = _norm_desc(descricao)
    if not norm or not categoria:
        return
    ja = con.execute(
        "SELECT id FROM aprendizado_categoria WHERE user_id=? AND descricao_norm=?", (user_id, norm)
    ).fetchone()
    if ja:
        con.execute("UPDATE aprendizado_categoria SET categoria=? WHERE id=?", (categoria, ja[0]))
    else:
        con.execute("INSERT INTO aprendizado_categoria (descricao_norm, categoria, user_id) VALUES (?, ?, ?)",
                    (norm, categoria, user_id))

def sugerir_categoria(con, user_id, descricao):
    """M2/M9: adivinha a categoria de um gasto livre. Primeiro pelo que o usuário JÁ ENSINOU
    (descrição igual), depois pela palavra na descrição (uber->transporte...). Só retorna se a
    categoria ainda existir. Retorna o nome real da categoria do usuário, ou None."""
    # M9: o que o usuário já ensinou pra essa descrição
    norm = _norm_desc(descricao)
    if norm:
        r = con.execute("SELECT categoria FROM aprendizado_categoria WHERE user_id=? AND descricao_norm=?", (user_id, norm)).fetchone()
        if r:
            ex = con.execute("SELECT nome FROM categorias WHERE user_id=? AND lower(nome)=lower(?)", (user_id, r[0])).fetchone()
            if ex:
                return ex[0]
    d = (descricao or "").lower()
    alvo = None
    for palavra, categoria in MAPA_PALAVRAS.items():
        if palavra in d:
            alvo = categoria
            break
    if not alvo:
        return None
    linha = con.execute(
        "SELECT nome FROM categorias WHERE user_id=? AND lower(nome)=lower(?)", (user_id, alvo)
    ).fetchone()
    return linha[0] if linha else None

def _sugerir_caixinha(descricao, caixinhas):
    """caixinhas = lista de (id, nome_minusculo). Retorna o id sugerido ou None."""
    d = (descricao or "").lower()
    for cid, nome in caixinhas:
        if nome and nome in d:
            return cid
    for palavra, categoria in MAPA_PALAVRAS.items():
        if palavra in d:
            for cid, nome in caixinhas:
                if nome == categoria:
                    return cid
    return None

def parse_ofx(texto, caixinhas):
    linhas = []
    for bloco in re.findall(r"<STMTTRN>(.*?)</STMTTRN>", texto, re.S | re.I):
        m_val = re.search(r"<TRNAMT>([^<\r\n]+)", bloco, re.I)
        if not m_val:
            continue
        valor = _num_br(m_val.group(1))
        if valor is None:
            continue
        m_dt = re.search(r"<DTPOSTED>(\d{8})", bloco, re.I)
        data = "?"
        if m_dt:
            g = m_dt.group(1)
            data = f"{g[0:4]}-{g[4:6]}-{g[6:8]}"
        m_memo = re.search(r"<MEMO>([^<\r\n]+)", bloco, re.I)
        m_name = re.search(r"<NAME>([^<\r\n]+)", bloco, re.I)
        desc = (m_memo.group(1) if m_memo else (m_name.group(1) if m_name else "lançamento")).strip()
        cents = abs(round(valor * 100))
        if cents == 0:
            continue
        linhas.append({
            "descricao": desc[:80],
            "valor_centavos": cents,
            "data": data,
            "tipo": "entrada" if valor > 0 else "pagamento",
            "caixinha_id": _sugerir_caixinha(desc, caixinhas),
        })
    return linhas

def parse_csv(texto, caixinhas):
    amostra = texto[:3000]
    delim = ";" if amostra.count(";") >= amostra.count(",") else ","
    linhas_raw = [r for r in csv.reader(io.StringIO(texto), delimiter=delim) if any((c or "").strip() for c in r)]
    if not linhas_raw:
        return []

    def achar(hs, termos):
        for i, h in enumerate(hs):
            for t in termos:
                if t in h:
                    return i
        return None

    header = [(c or "").strip().lower() for c in linhas_raw[0]]
    i_data = achar(header, ["data", "date"])
    i_valor = achar(header, ["valor", "amount", "quantia", "montante", "value"])
    i_desc = achar(header, ["descri", "histor", "lanç", "lanc", "memo", "estabelec", "title", "detalhe"])
    tem_cabecalho = (i_data is not None) or (i_valor is not None)
    corpo = linhas_raw[1:] if tem_cabecalho else linhas_raw

    linhas = []
    for r in corpo:
        valor = None
        data = "?"
        desc = "lançamento"
        if i_valor is not None and i_valor < len(r):
            valor = _num_br(r[i_valor])
            if i_data is not None and i_data < len(r):
                data = _data_iso(r[i_data])
            if i_desc is not None and i_desc < len(r):
                desc = (r[i_desc] or "").strip() or "lançamento"
        else:
            # heurística posicional: acha um token de data e um token monetário (com , ou .)
            partes = []
            for cel in r:
                c = (cel or "").strip()
                if data == "?" and _data_iso(c) != "?":
                    data = _data_iso(c); continue
                if valor is None and ("," in c or "." in c) and _num_br(c) is not None:
                    valor = _num_br(c); continue
                partes.append(c)
            desc = " ".join(p for p in partes if p) or "lançamento"
        if valor is None:
            continue
        cents = abs(round(valor * 100))
        if cents == 0:
            continue
        linhas.append({
            "descricao": desc[:80],
            "valor_centavos": cents,
            "data": data,
            "tipo": "entrada" if valor > 0 else "pagamento",
            "caixinha_id": _sugerir_caixinha(desc, caixinhas),
        })
    return linhas


