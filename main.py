class _ConexaoPG:
    """Faz a conexão psycopg2 se comportar como a do sqlite3 que o código usa:
    con.execute("... ?", (...)).fetchone()/fetchall(), con.commit(), con.close().
    Traduz '?' -> '%s' e devolve um cursor a cada execute."""
    def __init__(self):
        if psycopg2 is None:
            raise RuntimeError("psycopg2 não instalado — rode: pip install psycopg2-binary")
        self._con = psycopg2.connect(
            host=os.environ["PGHOST"],
            port=os.environ.get("PGPORT", "5432"),
            dbname=os.environ.get("PGDATABASE", "postgres"),
            user=os.environ["PGUSER"],
            password=os.environ["PGPASSWORD"],
            sslmode=os.environ.get("PGSSLMODE", "require"),
        )
    def execute(self, sql, params=()):
        cur = self._con.cursor()
        cur.execute(sql.replace("?", "%s"), params)
        return cur
    def commit(self):
        self._con.commit()
    def close(self):
        self._con.close()

def conectar():
    if USA_POSTGRES:
        return _ConexaoPG()
    return sqlite3.connect("financeiro.db")

# INSERT-ou-atualiza uma chave da config (dialetos diferentes entre SQLite e Postgres).
def _upsert_config(con, user_id, chave, valor):
    if USA_POSTGRES:
        con.execute("INSERT INTO config (user_id, chave, valor) VALUES (?, ?, ?) "
                    "ON CONFLICT (user_id, chave) DO UPDATE SET valor = EXCLUDED.valor", (user_id, chave, valor))
    else:
        con.execute("INSERT OR REPLACE INTO config (user_id, chave, valor) VALUES (?, ?, ?)", (user_id, chave, valor))

