@app.post("/contas/{conta_id}/pagar")
def pagar_conta(conta_id: int, item: PagamentoConta, user_id: str = Depends(exigir_login)):
    con = conectar()

    # a conta existe?
    conta = con.execute(
        "SELECT id, valor_centavos, paga, tipo_conta, nome FROM contas WHERE id=? AND user_id=?", (conta_id, user_id)
    ).fetchone()
    if conta is None:
        con.close()
        raise HTTPException(status_code=404, detail="Essa conta não existe.")

    # já foi paga?
    if conta[2] == 1:
        con.close()
        raise HTTPException(status_code=400, detail="Essa conta já foi paga.")

    # valor a pagar = o que FALTA (total menos o que já foi pago em parciais)
    total = total_conta(con, user_id, conta_id, conta[3] or "simples", conta[1])
    if total <= 0:
        con.close()
        raise HTTPException(status_code=400, detail="Essa fatura não tem itens para pagar.")
    valor = total - total_pago_conta(con, user_id, conta_id)
    if valor <= 0:
        con.close()
        raise HTTPException(status_code=400, detail="Essa conta já está quitada.")

    # a caixinha é do usuário e tem saldo suficiente?
    if con.execute("SELECT id FROM caixinhas WHERE id=? AND user_id=?", (item.caixinha_id, user_id)).fetchone() is None:
        con.close()
        raise HTTPException(status_code=404, detail="Caixinha não encontrada.")
    if saldo_da_caixinha(con, user_id, item.caixinha_id) < valor:
        con.close()
        raise HTTPException(status_code=400, detail="Saldo insuficiente nessa caixinha.")

    # tira o dinheiro da caixinha (pagamento) — a descrição carrega o NOME da conta
    # pra ficar claro no histórico o que foi pago (ex.: "Pagamento: Conta de luz").
    # conta_paga_id liga o pagamento à conta (base do cálculo de "quanto já foi pago").
    con.execute(
        "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, conta_paga_id, user_id) VALUES (?, ?, ?, ?, ?, ?, ?)",
        ("pagamento", valor, f"Pagamento: {conta[4]}", item.caixinha_id, data_hoje(), conta_id, user_id)
    )
    # marca a conta como paga e guarda de qual caixinha saiu
    con.execute(
        "UPDATE contas SET paga=1, caixinha_paga_id=? WHERE id=? AND user_id=?",
        (item.caixinha_id, conta_id, user_id)
    )
    con.commit()
    con.close()
    return {"status": "conta paga"}

@app.post("/contas/{conta_id}/pagar-parcial")
def pagar_conta_parcial(conta_id: int, item: PagamentoParcial, user_id: str = Depends(exigir_login)):
    """Paga PARTE de uma conta/fatura (ex.: R$100 de R$500). A conta continua na lista
    mostrando quanto falta, e só vira 'paga' quando a soma dos pagamentos atinge o total."""
    con = conectar()
    conta = con.execute(
        "SELECT id, valor_centavos, paga, tipo_conta, nome FROM contas WHERE id=? AND user_id=?", (conta_id, user_id)
    ).fetchone()
    if conta is None:
        con.close()
        raise HTTPException(status_code=404, detail="Essa conta não existe.")
    if conta[2] == 1:
        con.close()
        raise HTTPException(status_code=400, detail="Essa conta já foi paga.")
    if item.valor_centavos <= 0:
        con.close()
        raise HTTPException(status_code=400, detail="O valor a pagar precisa ser maior que zero.")

    total = total_conta(con, user_id, conta_id, conta[3] or "simples", conta[1])
    if total <= 0:
        con.close()
        raise HTTPException(status_code=400, detail="Essa fatura não tem itens para pagar.")
    restante = total - total_pago_conta(con, user_id, conta_id)
    if item.valor_centavos > restante:
        con.close()
        raise HTTPException(status_code=400, detail=f"Você só deve R$ {restante/100:.2f} nessa conta.")

    # caixinha do usuário e com saldo suficiente?
    if con.execute("SELECT id FROM caixinhas WHERE id=? AND user_id=?", (item.caixinha_id, user_id)).fetchone() is None:
        con.close()
        raise HTTPException(status_code=404, detail="Caixinha não encontrada.")
    if saldo_da_caixinha(con, user_id, item.caixinha_id) < item.valor_centavos:
        con.close()
        raise HTTPException(status_code=400, detail="Saldo insuficiente nessa caixinha.")

    quita = item.valor_centavos >= restante   # esse pagamento zera o que faltava?
    prefixo = "Pagamento" if quita else "Pagamento parcial"
    con.execute(
        "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, conta_paga_id, user_id) VALUES (?, ?, ?, ?, ?, ?, ?)",
        ("pagamento", item.valor_centavos, f"{prefixo}: {conta[4]}", item.caixinha_id, data_hoje(), conta_id, user_id)
    )
    if quita:
        con.execute(
            "UPDATE contas SET paga=1, caixinha_paga_id=? WHERE id=? AND user_id=?",
            (item.caixinha_id, conta_id, user_id)
        )
    con.commit()
    con.close()
    novo_restante = max(restante - item.valor_centavos, 0)
    return {"status": "pago" if quita else "pago parcialmente",
            "quitada": quita, "restante_reais": novo_restante / 100}

@app.post("/contas/{conta_id}/desfazer-pagamento")
def desfazer_pagamento(conta_id: int, user_id: str = Depends(exigir_login)):
    """Desfaz TODOS os pagamentos da conta (parciais e total): apaga os lançamentos
    ligados a ela — devolvendo o dinheiro às caixinhas de onde saiu — e volta a conta
    para não-paga. Funciona tanto numa conta quitada quanto numa parcialmente paga."""
    con = conectar()
    conta = con.execute(
        "SELECT id, valor_centavos, paga, caixinha_paga_id, tipo_conta, nome FROM contas WHERE id=? AND user_id=?", (conta_id, user_id)
    ).fetchone()
    if conta is None:
        con.close()
        raise HTTPException(status_code=404, detail="Essa conta não existe.")

    # 1) pagamentos ligados pela FK conta_paga_id (jeito novo: cobre parcial + total)
    ligados = con.execute(
        "SELECT id FROM lancamentos WHERE tipo='pagamento' AND conta_paga_id=? AND user_id=?",
        (conta_id, user_id)
    ).fetchall()
    for (lid,) in ligados:
        con.execute("DELETE FROM lancamentos WHERE id=? AND user_id=?", (lid, user_id))

    # 2) fallback p/ pagamentos ANTIGOS (feitos antes desta mudança, sem conta_paga_id):
    #    só se não havia nenhum ligado e a conta estava marcada como paga.
    if not ligados and conta[2] == 1:
        valor = total_conta(con, user_id, conta_id, conta[4] or "simples", conta[1])
        lanc = con.execute(
            "SELECT id FROM lancamentos WHERE caixinha_id=? AND valor_centavos=? AND tipo='pagamento' "
            "AND descricao IN (?, 'pagamento de conta') AND user_id=? ORDER BY id DESC LIMIT 1",
            (conta[3], valor, f"Pagamento: {conta[5]}", user_id)
        ).fetchone()
        if lanc is not None:
            con.execute("DELETE FROM lancamentos WHERE id=? AND user_id=?", (lanc[0], user_id))
    elif not ligados and conta[2] == 0:
        con.close()
        raise HTTPException(status_code=400, detail="Essa conta não tem pagamentos para desfazer.")

    # marca a conta como não paga de novo
    con.execute("UPDATE contas SET paga=0, caixinha_paga_id=NULL WHERE id=? AND user_id=?", (conta_id, user_id))
    con.commit()
    con.close()
    return {"status": "pagamento desfeito"}


