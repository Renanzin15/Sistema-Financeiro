def listar_regras(user_id: str = Depends(exigir_login)):
    con = conectar()
    linhas = con.execute(
        "SELECT id, gatilho, modo, valor, caixinha_id FROM regras_salario WHERE user_id=? ORDER BY id",
        (user_id,)
    ).fetchall()
    con.close()
    return [
        {"id": l[0], "gatilho": l[1], "modo": l[2], "valor": l[3], "caixinha_id": l[4]}
        for l in linhas
    ]

@app.post("/regras")
def criar_regra(item: NovaRegra, user_id: str = Depends(exigir_login)):
    gatilho = item.gatilho.strip()
    if not gatilho:
        raise HTTPException(status_code=400, detail="Informe o nome do gatilho (ex.: Salário).")
    if item.modo not in ("percentual", "fixo"):
        raise HTTPException(status_code=400, detail="Modo inválido.")
    if item.valor <= 0:
        raise HTTPException(status_code=400, detail="O valor precisa ser maior que zero.")
    if item.modo == "percentual" and item.valor > 100:
        raise HTTPException(status_code=400, detail="A porcentagem não pode passar de 100%.")
    con = conectar()
    existe = con.execute("SELECT id FROM caixinhas WHERE id=? AND user_id=?", (item.caixinha_id, user_id)).fetchone()
    if existe is None:
        con.close()
        raise HTTPException(status_code=400, detail="Essa caixinha não existe.")
    con.execute(
        "INSERT INTO regras_salario (gatilho, modo, valor, caixinha_id, user_id) VALUES (?, ?, ?, ?, ?)",
        (gatilho, item.modo, item.valor, item.caixinha_id, user_id)
    )
    con.commit()
    con.close()
    return {"status": "regra criada"}

@app.delete("/regras/{regra_id}")
def apagar_regra(regra_id: int, user_id: str = Depends(exigir_login)):
    con = conectar()
    existe = con.execute("SELECT id FROM regras_salario WHERE id=? AND user_id=?", (regra_id, user_id)).fetchone()
    if existe is None:
        con.close()
        raise HTTPException(status_code=404, detail="Essa regra não existe.")
    con.execute("DELETE FROM regras_salario WHERE id=? AND user_id=?", (regra_id, user_id))
    con.commit()
    con.close()
    return {"status": "regra apagada"}


