_MESES_PERIODO = {"mensal": 1, "trimestral": 3, "semestral": 6, "anual": 12}

def _avancar_periodo(data_iso, periodicidade):
    """Avança uma data AAAA-MM-DD pelo período (1/3/6/12 meses), ajustando fim de mês
    (ex.: 31/01 + 1 mês -> 28/02)."""
    meses = _MESES_PERIODO.get(periodicidade, 1)
    y, m, d = (int(x) for x in data_iso.split("-"))
    total = (m - 1) + meses
    ny = y + total // 12
    nm = total % 12 + 1
    nd = min(d, calendar.monthrange(ny, nm)[1])
    return f"{ny:04d}-{nm:02d}-{nd:02d}"

