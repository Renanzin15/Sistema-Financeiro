# E4: aplica as regras de salário a uma entrada recém-registrada.
# Para cada regra cujo gatilho bate (ignora maiúsc/minúsc) com a descrição da entrada,
# cria uma alocação automática na caixinha indicada (% do valor ou valor fixo).
def aplicar_regras_salario(con, user_id, descricao, valor_centavos, data):
    alvo = (descricao or "").strip().lower()
    if not alvo:
        return
    regras = con.execute(
        "SELECT modo, valor, caixinha_id FROM regras_salario WHERE user_id=? AND lower(gatilho)=?",
        (user_id, alvo)
    ).fetchall()
    for modo, valor, cxid in regras:
        if cxid is None:
            continue
        cx = con.execute("SELECT nome FROM caixinhas WHERE id=? AND user_id=?", (cxid, user_id)).fetchone()
        if cx is None:
            continue
        nome_cx = cx[0]
        if modo == "percentual":
            quantia = round(valor_centavos * valor / 100)
        else:
            quantia = valor
        if quantia <= 0:
            continue
        # rótulo claro no histórico: mostra o gatilho e a caixinha de destino (ex.: "Regra salário → Reserva")
        con.execute(
            "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, user_id) VALUES ('alocacao', ?, ?, ?, ?, ?)",
            (quantia, f"Regra {descricao.strip()} → {nome_cx}", cxid, data, user_id)
        )

# gera as ENTRADAS recorrentes (renda automática, ex.: salário todo dia 5) do mês atual:
# para cada uma cujo dia já chegou, cria uma 'entrada' (1x por mês, sem duplicar) e DISPARA as
# regras de distribuição — se o nome bater com um gatilho, o dinheiro já se espalha nas caixinhas.
def gerar_entradas_recorrentes(user_id):
    con = conectar()
    hoje = date.today()
    mes_str = f"{hoje.year:04d}-{hoje.month:02d}"
    # último dia do mês (pra caber dia 31 em meses curtos)
    prox = date(hoje.year + 1, 1, 1) if hoje.month == 12 else date(hoje.year, hoje.month + 1, 1)
    ultimo_dia = (prox - timedelta(days=1)).day
    itens = con.execute(
        "SELECT nome, valor_centavos, dia, criada_em FROM entradas_recorrentes WHERE user_id=?", (user_id,)
    ).fetchall()
    for nome, valor, dia, criada_em in itens:
        if not valor or valor <= 0 or not dia:
            continue
        dia_ok = min(int(dia), ultimo_dia)
        if hoje.day < dia_ok:
            continue  # ainda não chegou o dia neste mês
        data = f"{mes_str}-{dia_ok:02d}"
        # NÃO lança retroativo: se a renda foi criada depois da data de vencimento deste mês
        # (ex.: cadastrou dia 13 uma renda de dia 5), só começa a partir do próximo mês.
        if criada_em and data < criada_em:
            continue
        # já lançada este mês? (dedup por nome + mês)
        ja = con.execute(
            "SELECT id FROM lancamentos WHERE user_id=? AND tipo='entrada' AND descricao=? AND data LIKE ?",
            (user_id, nome, mes_str + "%")
        ).fetchone()
        if ja is not None:
            continue
        con.execute(
            "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, user_id) VALUES ('entrada', ?, ?, NULL, ?, ?)",
            (valor, nome, data, user_id)
        )
        # dispara as regras de distribuição (mesma lógica de uma entrada manual)
        aplicar_regras_salario(con, user_id, nome, valor, data)
    con.commit()
    con.close()

