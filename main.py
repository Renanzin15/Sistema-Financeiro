# valida uma data recebida: vazia (usa hoje) OU no formato AAAA-MM-DD com ano plausível.
# evita "datas malucas" (ex.: ano 1990, texto solto) que quebrariam agrupamentos/ordem.
def data_valida(s):
    if not s:
        return True
    m = re.match(r"^(\d{4})-(\d{2})-(\d{2})$", s)
    if not m:
        return False
    ano, mes, dia = int(m.group(1)), int(m.group(2)), int(m.group(3))
    if not (2000 <= ano <= 2100 and 1 <= mes <= 12 and 1 <= dia <= 31):
        return False
    return True

# saldo de uma caixinha = (alocações + rendimentos) menos pagamentos dela.
# M2: 'rendimento' (ex.: CDI) entra na caixinha como dinheiro novo — por isso soma aqui,
# mas NÃO conta como 'entrada' (não infla "Entrou no mês") nem sai do saldo livre.
def saldo_da_caixinha(con, user_id, caixinha_id):
    entrou = con.execute(
        "SELECT COALESCE(SUM(valor_centavos),0) FROM lancamentos WHERE caixinha_id=? AND user_id=? AND tipo IN ('alocacao','rendimento')",
        (caixinha_id, user_id)
    ).fetchone()[0]
    saiu = con.execute(
        "SELECT COALESCE(SUM(valor_centavos),0) FROM lancamentos WHERE caixinha_id=? AND user_id=? AND tipo='pagamento'",
        (caixinha_id, user_id)
    ).fetchone()[0]
    return entrou - saiu

# D: total de uma conta. Fatura = soma dos itens; simples = o valor guardado.
def total_conta(con, user_id, conta_id, tipo_conta, valor_centavos):
    if tipo_conta == "fatura":
        return con.execute(
            "SELECT COALESCE(SUM(valor_centavos),0) FROM fatura_itens WHERE conta_id=? AND user_id=?",
            (conta_id, user_id)
        ).fetchone()[0]
    return valor_centavos

# E4: aplica as regras de salário a uma entrada recém-registrada.
# Para cada regra cujo gatilho bate (ignora maiúsc/minúsc) com a descrição da entrada,
# cria uma alocação automática na caixinha indicada (% do valor ou valor fixo).
def aplicar_regras_salario(con, user_id, descricao, valor_centavos, data):
    alvo = (descricao or "").strip().lower()
    if not alvo:
        return
    regras = con.execute(
        "SELECT modo, valor, caixinha_id FROM regras_salario WHERE user_id=? AND lower(gatilho)=?",
        (user_id, alvo)
    ).fetchall()
    for modo, valor, cxid in regras:
        if cxid is None:
            continue
        existe = con.execute("SELECT id FROM caixinhas WHERE id=? AND user_id=?", (cxid, user_id)).fetchone()
        if existe is None:
            continue
        if modo == "percentual":
            quantia = round(valor_centavos * valor / 100)
        else:
            quantia = valor
        if quantia <= 0:
            continue
        con.execute(
            "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, user_id) VALUES ('alocacao', ?, ?, ?, ?, ?)",
            (quantia, f"regra: {descricao.strip()}", cxid, data, user_id)
        )

# gera as cobranças das recorrentes para o mês atual (uma vez por mês, sem duplicar).
# E2: se a assinatura está vinculada a uma fatura de cartão, ela entra como ITEM dessa
# fatura (soma no cartão) em vez de virar uma conta avulsa. Se estiver avulsa, cria a conta.
def gerar_recorrentes_do_mes(user_id):
    con = conectar()
    hoje = date.today()
    ano = hoje.year
    mes = hoje.month
    mes_str = f"{ano:04d}-{mes:02d}"
    recorrentes = con.execute(
        "SELECT nome, valor_centavos, dia_vencimento, tipo, conta_fatura_id FROM recorrentes WHERE user_id=?",
        (user_id,)
    ).fetchall()
    for nome, valor, dia, tipo, fatura_id in recorrentes:
        vencimento = f"{ano:04d}-{mes:02d}-{dia:02d}"
        if fatura_id is not None:
            fatura = con.execute(
                "SELECT id, tipo_conta, paga FROM contas WHERE id=? AND user_id=?", (fatura_id, user_id)
            ).fetchone()
            # vinculada a uma fatura VÁLIDA -> vira item dela (nunca cria conta avulsa)
            if fatura is not None and (fatura[1] or "simples") == "fatura":
                if fatura[2] == 0:  # só mexe na fatura se ainda não foi paga
                    ja_item = con.execute(
                        "SELECT id FROM fatura_itens WHERE conta_id=? AND descricao=? AND data LIKE ? AND user_id=?",
                        (fatura_id, nome, mes_str + "%", user_id)
                    ).fetchone()
                    if ja_item is None:
                        con.execute(
                            "INSERT INTO fatura_itens (conta_id, descricao, valor_centavos, data, user_id) VALUES (?, ?, ?, ?, ?)",
                            (fatura_id, nome, valor, vencimento, user_id)
                        )
                continue
            # fatura apagada ou inválida -> cai no comportamento avulso abaixo
        ja_existe = con.execute(
            "SELECT id FROM contas WHERE nome=? AND vencimento=? AND user_id=?",
            (nome, vencimento, user_id)
        ).fetchone()
        if ja_existe is None:
            con.execute(
                "INSERT INTO contas (nome, valor_centavos, vencimento, tipo, user_id) VALUES (?, ?, ?, ?, ?)",
                (nome, valor, vencimento, tipo, user_id)
            )
    con.commit()
    con.close()


