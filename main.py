@app.post("/transferir")
def transferir(item: NovaTransferencia, user_id: str = Depends(exigir_login)):
    if item.valor_centavos <= 0:
        raise HTTPException(status_code=400, detail="O valor precisa ser maior que zero.")
    if item.origem_id == item.destino_id:
        raise HTTPException(status_code=400, detail="Origem e destino não podem ser a mesma caixinha.")

    con = conectar()

    # origem e destino precisam pertencer ao usuário
    for _cid in (item.origem_id, item.destino_id):
        if con.execute("SELECT id FROM caixinhas WHERE id=? AND user_id=?", (_cid, user_id)).fetchone() is None:
            con.close()
            raise HTTPException(status_code=404, detail="Caixinha não encontrada.")

    saldo_origem = saldo_da_caixinha(con, user_id, item.origem_id)
    if saldo_origem < item.valor_centavos:
        con.close()
        raise HTTPException(status_code=400, detail="Saldo insuficiente na caixinha de origem.")

    # tira da origem (pagamento) e põe no destino (alocacao)
    hoje = data_hoje()
    con.execute(
        "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, user_id) VALUES (?, ?, ?, ?, ?, ?)",
        ("pagamento", item.valor_centavos, "transferência (saída)", item.origem_id, hoje, user_id)
    )
    con.execute(
        "INSERT INTO lancamentos (tipo, valor_centavos, descricao, caixinha_id, data, user_id) VALUES (?, ?, ?, ?, ?, ?)",
        ("alocacao", item.valor_centavos, "transferência (entrada)", item.destino_id, hoje, user_id)
    )
    con.commit()
    con.close()
    return {"status": "transferência feita"}

